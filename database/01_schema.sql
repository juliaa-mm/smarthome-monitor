SET client_min_messages = warning;

DROP VIEW  IF EXISTS v_latest_readings, v_events_full, v_room_device_states CASCADE;
DROP TABLE IF EXISTS app_users, automation_scenarios, state_history, events,
    event_types, sensor_readings, device_parameters, parameters, devices,
    rooms, device_types, houses CASCADE;

CREATE TABLE houses (
    house_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name      VARCHAR(100) NOT NULL,
    address   VARCHAR(200) NOT NULL,
    city      VARCHAR(100) NOT NULL,
    CONSTRAINT pk_houses PRIMARY KEY (house_id),
    CONSTRAINT uq_houses_address UNIQUE (address)
);

CREATE TABLE device_types (
    type_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(100) NOT NULL,
    category    VARCHAR(100) NOT NULL,
    description VARCHAR(300),
    CONSTRAINT pk_device_types PRIMARY KEY (type_id),
    CONSTRAINT uq_device_types_name UNIQUE (name)
);

CREATE TABLE parameters (
    parameter_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name         VARCHAR(100) NOT NULL,
    unit         VARCHAR(20)  NOT NULL,
    CONSTRAINT pk_parameters PRIMARY KEY (parameter_id),
    CONSTRAINT uq_parameters_name UNIQUE (name)
);

CREATE TABLE event_types (
    event_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR(100) NOT NULL,
    description   VARCHAR(300),
    CONSTRAINT pk_event_types PRIMARY KEY (event_type_id),
    CONSTRAINT uq_event_types_name UNIQUE (name)
);

CREATE TABLE rooms (
    room_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    house_id INTEGER  NOT NULL,
    name     VARCHAR(100) NOT NULL,
    floor    SMALLINT DEFAULT 1 NOT NULL,
    CONSTRAINT pk_rooms PRIMARY KEY (room_id),
    CONSTRAINT fk_rooms_house FOREIGN KEY (house_id) REFERENCES houses (house_id),
    CONSTRAINT uq_rooms_house_name UNIQUE (house_id, name),
    CONSTRAINT ck_rooms_floor CHECK (floor BETWEEN 0 AND 50)
);

CREATE TABLE devices (
    device_id     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    room_id       INTEGER      NOT NULL,
    type_id       INTEGER      NOT NULL,
    name          VARCHAR(150) NOT NULL,
    manufacturer  VARCHAR(100),
    serial_number VARCHAR(50)  NOT NULL,
    install_date  DATE         DEFAULT CURRENT_DATE NOT NULL,
    current_state VARCHAR(10)  DEFAULT 'OFF' NOT NULL,
    work_mode     VARCHAR(10)  DEFAULT 'MANUAL' NOT NULL,
    CONSTRAINT pk_devices PRIMARY KEY (device_id),
    CONSTRAINT fk_devices_room FOREIGN KEY (room_id) REFERENCES rooms (room_id),
    CONSTRAINT fk_devices_type FOREIGN KEY (type_id) REFERENCES device_types (type_id),
    CONSTRAINT uq_devices_serial UNIQUE (serial_number),
    CONSTRAINT ck_devices_state CHECK (current_state IN ('ON', 'OFF', 'ERROR', 'OFFLINE')),
    CONSTRAINT ck_devices_work_mode CHECK (work_mode IN ('AUTO', 'MANUAL'))
);

CREATE TABLE device_parameters (
    device_parameter_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    device_id           INTEGER NOT NULL,
    parameter_id        INTEGER NOT NULL,
    CONSTRAINT pk_device_parameters PRIMARY KEY (device_parameter_id),
    CONSTRAINT fk_dp_device FOREIGN KEY (device_id) REFERENCES devices (device_id),
    CONSTRAINT fk_dp_parameter FOREIGN KEY (parameter_id) REFERENCES parameters (parameter_id),
    CONSTRAINT uq_dp_device_param UNIQUE (device_id, parameter_id)
);

CREATE TABLE sensor_readings (
    reading_id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    device_parameter_id INTEGER       NOT NULL,
    value               NUMERIC(8, 2) NOT NULL,
    reading_time        TIMESTAMP(0)  DEFAULT LOCALTIMESTAMP(0) NOT NULL,
    CONSTRAINT pk_sensor_readings PRIMARY KEY (reading_id),
    CONSTRAINT fk_readings_dp FOREIGN KEY (device_parameter_id)
        REFERENCES device_parameters (device_parameter_id)
);

CREATE TABLE automation_scenarios (
    scenario_id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name               VARCHAR(150) NOT NULL,
    description        VARCHAR(300),
    trigger_condition  VARCHAR(200) NOT NULL,
    action_description VARCHAR(200) NOT NULL,
    is_active          SMALLINT DEFAULT 1 NOT NULL,
    room_id            INTEGER,
    device_id          INTEGER,
    CONSTRAINT pk_automation_scenarios PRIMARY KEY (scenario_id),
    CONSTRAINT fk_scenarios_room FOREIGN KEY (room_id) REFERENCES rooms (room_id),
    CONSTRAINT fk_scenarios_device FOREIGN KEY (device_id) REFERENCES devices (device_id),
    CONSTRAINT ck_scenarios_active CHECK (is_active IN (0, 1)),
    CONSTRAINT ck_scenarios_target CHECK (room_id IS NOT NULL OR device_id IS NOT NULL)
);

CREATE TABLE events (
    event_id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    device_id     INTEGER      NOT NULL,
    event_type_id INTEGER      NOT NULL,
    event_time    TIMESTAMP(0) DEFAULT LOCALTIMESTAMP(0) NOT NULL,
    description   VARCHAR(300),
    scenario_id   INTEGER,
    CONSTRAINT pk_events PRIMARY KEY (event_id),
    CONSTRAINT fk_events_device FOREIGN KEY (device_id) REFERENCES devices (device_id),
    CONSTRAINT fk_events_type FOREIGN KEY (event_type_id) REFERENCES event_types (event_type_id),
    CONSTRAINT fk_events_scenario FOREIGN KEY (scenario_id)
        REFERENCES automation_scenarios (scenario_id)
);

CREATE TABLE state_history (
    history_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    device_id  INTEGER      NOT NULL,
    old_state  VARCHAR(10)  NOT NULL,
    new_state  VARCHAR(10)  NOT NULL,
    changed_at TIMESTAMP(0) DEFAULT LOCALTIMESTAMP(0) NOT NULL,
    CONSTRAINT pk_state_history PRIMARY KEY (history_id),
    CONSTRAINT fk_history_device FOREIGN KEY (device_id) REFERENCES devices (device_id),
    CONSTRAINT ck_history_old CHECK (old_state IN ('ON', 'OFF', 'ERROR', 'OFFLINE')),
    CONSTRAINT ck_history_new CHECK (new_state IN ('ON', 'OFF', 'ERROR', 'OFFLINE')),
    CONSTRAINT ck_history_diff CHECK (old_state <> new_state)
);

CREATE TABLE app_users (
    user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    login         VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(150) NOT NULL,
    role          VARCHAR(10)  DEFAULT 'VIEWER' NOT NULL,
    created_at    TIMESTAMP(0) DEFAULT LOCALTIMESTAMP(0) NOT NULL,
    CONSTRAINT pk_app_users PRIMARY KEY (user_id),
    CONSTRAINT uq_app_users_login UNIQUE (login),
    CONSTRAINT ck_app_users_role CHECK (role IN ('ADMIN', 'VIEWER'))
);

CREATE INDEX ix_devices_room      ON devices (room_id);
CREATE INDEX ix_devices_type      ON devices (type_id);
CREATE INDEX ix_events_device     ON events (device_id);
CREATE INDEX ix_events_time       ON events (event_time DESC);
CREATE INDEX ix_readings_dp_time  ON sensor_readings (device_parameter_id, reading_time DESC);
CREATE INDEX ix_history_device    ON state_history (device_id, changed_at DESC);
